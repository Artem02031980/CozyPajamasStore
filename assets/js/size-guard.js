/**
 * size-guard.js — «Выберите размер»: одно правило для всех покупок.
 *
 * На странице товара размер выбирают на месте, рядом с кнопками. И «Добавить
 * в корзину», и «Купить в один клик» без размера работать не должны: позиция
 * без размера — это позиция, которую нельзя ни отправить, ни примерить,
 * а человек даже не заметит, что не выбрал.
 *
 * Правило включается разметкой, а не кодом: если рядом с кнопкой есть
 * элемент с data-size-error, значит для этой кнопки размер обязателен,
 * и текст сообщения лежит в этом элементе. Поэтому модуль не знает ни про
 * размеры, ни про то, как они называются на странице, а кнопки без такого
 * элемента (карточки каталога, услуга «ПРИНТ») работают как раньше.
 *
 * Пользуются обе покупки: cart-ui.js перед добавлением в корзину,
 * checkout.js перед покупкой в один клик.
 */

/** Селекторы правила: сообщение, ряд размеров и выбранный размер. */
const SELECTOR = {
  error: '[data-size-error]',
  size: '[data-product-size]',
};

/**
 * Проверяет размер перед покупкой и показывает сообщение, если его нет.
 *
 * Область поиска — карточка товара (`<article>`), в которой лежит кнопка:
 * на странице товара одна карточка, и сообщение с рядом размеров стоят
 * в ней же. Фокус уходит на первый размер: сообщение объясняет, что делать,
 * а фокус избавляет от поиска ряда.
 *
 * @param {HTMLElement} trigger кнопка покупки
 * @returns {boolean} true, если покупку нужно прервать
 */
export function blockWithoutSize(trigger) {
  if (!trigger) return false;

  const scope = trigger.closest('article') ?? document;
  const box = scope.querySelector(SELECTOR.error);

  /* Сообщения нет — размер для этой кнопки не обязателен */
  if (!box) return false;

  /* Размер выбран — покупка идёт как обычно */
  if (trigger.dataset.cartSize) return false;

  box.hidden = false;
  scope.querySelector(SELECTOR.size)?.focus();

  return true;
}

/**
 * Прячет сообщение: размер выбрали, и держать ошибку незачем.
 * Ошибка уходит сразу при выборе, не дожидаясь повторного нажатия, —
 * то же правило, что у ошибок форм.
 *
 * @param {HTMLElement} [root=document] где искать сообщение
 */
export function clearSizeError(root = document) {
  const box = root.querySelector?.(SELECTOR.error);
  if (box) box.hidden = true;
}
