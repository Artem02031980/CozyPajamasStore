/** Принт по идентификатору: по нему корзина находит позицию. */
export function getPrint(id) {
  return PRINTS.find((print) => print.id === id) ?? null;
}

/** Подпись принта для корзины и скринридера: «Принт 01. Good Morning!». */
export function printLabel(print) {
  const number = String(print.number).padStart(2, '0');
  return `Принт ${number}. ${print.title}`;
}

